import SwiftUI
import UIKit

/// Раздел 13, экран 1 ТЗ v1.2: что делает приложение, как назначить его
/// стандартным переводчиком, как настроить автоматизацию, блок приватности.
///
/// Deep link конкретно в «Настройки → Приложения → Приложения по умолчанию
/// → Перевод» Apple не публикует — есть только `openSettingsURLString`
/// (открывает страницу приложения в Настройках, не системный список
/// стандартных программ). Поэтому кнопка ведёт туда, а дальше — текстовые
/// шаги, проверенные вживую на iOS 18.4: `Настройки → Приложения →
/// Приложения по умолчанию → Перевод`.
struct OnboardingView: View {
    var body: some View {
        Form {
            Section("Что это такое") {
                Text("BYO Translate — переводчик для собственного API-ключа. Вы задаёте провайдера (OpenAI-совместимый, Anthropic или Google Gemini) и модель, приложение отправляет туда выделенный текст или изображение и показывает перевод.")
            }

            Section {
                Text("BYO Translate работает как стандартный системный переводчик — через выделение текста в любом приложении, не только внутри себя.")
                Button("Открыть настройки") {
                    if let url = URL(string: UIApplication.openSettingsURLString) {
                        UIApplication.shared.open(url)
                    }
                }
                VStack(alignment: .leading, spacing: 4) {
                    Text("Если сразу переключателя нет:")
                        .font(.caption)
                        .foregroundStyle(.secondary)
                    Text("Настройки → Приложения → Приложения по умолчанию → Перевод → BYO Translate")
                        .font(.caption.monospaced())
                        .foregroundStyle(.secondary)
                }
            } header: {
                Text("Как назначить стандартным переводчиком")
            }

            Section {
                Text("Два варианта — в зависимости от того, важно ли не сохранять скриншот в «Фото».")
                    .font(.callout)
                    .foregroundStyle(.secondary)
            } header: {
                Text("Автоматизация: скриншоты")
            }

            Section {
                VStack(alignment: .leading, spacing: 4) {
                    Text("Команда «Перевести скриншот» сама берёт последний снимок из «Фото» — собирать ничего не нужно, готова сразу:")
                    Text("1. Настройки → Пункт управления → добавить «Перевести скриншот».")
                    Text("2. Или: Настройки → Кнопка действия → выбрать «Перевести скриншот» (если на устройстве есть кнопка «Действие»).")
                }
                .font(.callout)
            } header: {
                Text("Быстрый вариант — через «Фото»")
            }

            Section {
                VStack(alignment: .leading, spacing: 4) {
                    Text("Команда «Перевести изображение» сама по себе не запускается — она принимает изображение из предыдущего шага. Чтобы получить снимок экрана, не сохраняя его в «Фото», нужно один раз собрать свою команду:")
                    Text("1. Приложение «Команды» → «+» → добавить действие «Сделать снимок экрана».")
                    Text("2. Следующим действием добавить «Перевести изображение» (BYO Translate).")
                    Text("3. Назначить получившуюся команду на кнопку «Действие» или в Пункт управления — так же, как обычную.")
                }
                .font(.callout)
            } header: {
                Text("Без сохранения в «Фото»")
            }

            Section {
                Text("Обе команды («Перевести скриншот» и «Перевести изображение») видны в приложении «Команды» сразу после установки — можно вызывать их голосом через Siri.")
                    .font(.callout)
                    .foregroundStyle(.secondary)
            }

            Section {
                Text("Выделенный текст и изображения отправляются напрямую на endpoint, который вы указали в настройках модели — и никуда больше. Ключ хранится в Keychain, не в логах и не в файлах. Кэш переводов (по умолчанию выключен) — единственное исключение из «ничего не сохраняется на диске»: если включить, переводы текста хранятся зашифрованными сутки, чтобы повтор того же текста был мгновенным.")
            } header: {
                Text("Приватность")
            }
        }
        .navigationTitle("Как начать")
    }
}
